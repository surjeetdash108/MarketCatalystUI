#!/usr/bin/env bash
# Copy the Strategy Lab engine to the backend, which runs the same file for the
# server-side universe runner. Run from MarketCatalystUI/ after editing
# app/iq/sl/engine.js. Also records the source's sha256 in both repos; the
# engine-sync tests (tests/strategy-lab/engine-sync.test.mjs here,
# src/live/strategy-lab/engine-sync.spec.ts in the backend) fail on any drift.
set -euo pipefail
BE="../MarketCatalystBackEnd/src/live/strategy-lab"
mkdir -p "$BE"
{ printf '%s\n' "/* eslint-disable */" "// @ts-nocheck — GENERATED by MarketCatalystUI/scripts/strategy-lab/sync-engine.sh: a copy of" "// MarketCatalystUI/app/iq/sl/engine.js. Edit that file, then re-run the script." ""; cat app/iq/sl/engine.js; } > "$BE/engine.ts"
SUM=$(shasum -a 256 app/iq/sl/engine.js | cut -d' ' -f1)
echo "$SUM" > app/iq/sl/engine.sha256
echo "$SUM" > "$BE/engine.sha256"
echo "synced $BE/engine.ts ($SUM)"
