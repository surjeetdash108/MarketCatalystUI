#!/usr/bin/env bash
# Regenerate Strategy Lab (app/iq/sl/{engine.js,lab-view.jsx,lab-controller.jsx})
# from the prototype HTML at the repo root. Run from MarketCatalystUI/.
set -euo pipefail
# RETIRED: the prototype HTML this reads is no longer in the workspace, and the
# port in app/iq/sl/ is now maintained by hand (engine fixes, results panel,
# saved strategies). Regenerating would overwrite that work. To copy the engine
# to the backend use scripts/strategy-lab/sync-engine.sh.
if [ "${STRATEGY_LAB_FORCE_REGENERATE:-}" != "1" ]; then
  echo "build.sh is retired (see header). Use sync-engine.sh for the backend engine copy." >&2
  exit 1
fi
HTML="${1:-../Strategy AI Lab - MarketCatalyst.html}"
WORK="$(mktemp -d)"
DIR="$(cd "$(dirname "$0")" && pwd)"
python3 -I "$DIR/extract.py" "$HTML" "$WORK"
# Performance fix, numerically identical: the prototype recomputed the 26-period
# EMA for every bar inside the MACD map (quadratic). Hoisting it keeps the exact
# values, including JS's null→0 coercion for the first 25 bars.
python3 -I - "$WORK/engine.js" <<'PY'
import sys
p = sys.argv[1]; s = open(p).read()
old = "const m = ema(c, 12).map((v, i) => v == null ? null : v - ema(c, 26)[i]);"
new = "const e26 = ema(c, 26), m = ema(c, 12).map((v, i) => v == null ? null : v - e26[i]);"
assert s.count(old) == 1, "MACD line changed in the prototype"
open(p, "w").write(s.replace(old, new))
PY
{ printf '%s\n' "// Strategy Lab backtest engine — ported verbatim from the Strategy AI Lab prototype" "// (\"Strategy AI Lab - MarketCatalyst.html\", resource btEngine) by scripts/strategy-lab/build.sh." "// Keep the logic identical to the prototype; the original header follows." ""; cat "$WORK/engine.js"; } > app/iq/sl/engine.js
python3 -I "$DIR/convert_view.py" "$WORK/lab.html" app/iq/sl/lab-view.jsx
python3 -I "$DIR/assemble_logic.py" "$WORK/app.js" app/iq/sl/lab-controller.jsx
# Backend copies: the same engine (type-checking off — it is the prototype's
# untyped JS) and the strategy definitions, for server-side universe backtests.
BE="../MarketCatalystBackEnd/src/live/strategy-lab"
mkdir -p "$BE"
{ printf '%s\n' "/* eslint-disable */" "// @ts-nocheck — GENERATED by MarketCatalystUI/scripts/strategy-lab/build.sh: the Strategy Lab" "// engine, identical to MarketCatalystUI/app/iq/sl/engine.js (verbatim prototype JS)." ""; cat app/iq/sl/engine.js; } > "$BE/engine.ts"
node "$DIR/extract_strategies.js" "$WORK/app.js" "$BE/strategies.ts"
rm -rf "$WORK"
