// Emit the Strategy Lab strategy definitions (key, candle, name, rules) as a
// TypeScript module for the backend, from the prototype's logic script — the
// same definitions the UI's lab-controller.jsx uses.
// Usage: node extract_strategies.js app.js out.ts
const fs = require("fs");
const [src, out] = process.argv.slice(2);
const L = fs.readFileSync(src, "utf8").split("\n");
const helpers = L[3]; // const _o=…,_v=…,_c=…,CL=…
const libStart = L.findIndex((l) => l.startsWith("const LIB=["));
const libEnd = L.findIndex((l, i) => i > libStart && l === "];");
const sStart = L.findIndex((l) => l.trim() === "const S=[");
const sEnd = L.findIndex((l, i) => i > sStart && l.trim() === "];");
if (!helpers.startsWith("const _o=") || libStart < 0 || libEnd < 0 || sStart < 0 || sEnd < 0) throw new Error("prototype layout changed");
const code = [helpers, ...L.slice(libStart, libEnd + 1), ...L.slice(sStart, sEnd + 1).map((l) => l.replace(/^\s*const S=\[/, "const S=[")), "return {LIB,S};"].join("\n");
const { LIB, S } = new Function(code)();
const all = [...S, ...LIB.filter((x) => !S.some((y) => y.k === x.k))].map((x) => ({ k: x.k, tf: x.tf || "d", name: x.name, cond: x.cond }));
fs.writeFileSync(out, `/* eslint-disable */
// GENERATED by MarketCatalystUI/scripts/strategy-lab/build.sh (extract_strategies.js)
// from the Strategy AI Lab prototype — the same strategy list, in the same order,
// as the UI's lab-controller.jsx (headline strategies first, then the library).
export interface LabCond { a?: any; op?: string; b?: any; any?: LabCond[] }
export interface LabStrategy { k: string; tf: string; name: string; cond: { entry: LabCond[]; exit: LabCond[] } }
export const LAB_STRATEGIES: LabStrategy[] = ${JSON.stringify(all, null, 1)};
`);
console.log("strategies:", all.length);
